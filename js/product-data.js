export function getProductByModelFile(
  modelFile
) {
  return (
    products.find(
      (product) =>
        product.modelFile ===
        modelFile
    ) ||
    null
  );
}


export function getProductBySlug(
  slug
) {
  return (
    products.find(
      (product) =>
        product.slug ===
        slug
    ) ||
    null
  );
}


export function formatProductPrice(
  product
) {
  if (
    !product ||
    typeof product.price !==
      "number"
  ) {
    return "";
  }

  return new Intl.NumberFormat(
    "en-IE",
    {
      style: "currency",

      currency:
        product.currency ||
        "EUR",

      maximumFractionDigits: 0
    }
  ).format(
    product.price
  );
}